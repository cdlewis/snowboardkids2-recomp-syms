#!/usr/bin/env python3
"""Dump a matching ELF, apply manual functions, and write stable symbol TOMLs."""

import argparse
import json
from pathlib import Path
import subprocess
import tempfile
import tomllib


def apply_manual(sections, manual_sections):
    for manual in manual_sections:
        section = next(s for s in sections if s["name"] == manual["name"])
        for function in manual["functions"]:
            start = function["vram"]
            end = start + function["size"]
            if not section["vram"] <= start < end <= section["vram"] + section["size"]:
                raise ValueError(f'Manual function outside section: {function["name"]}')
            for other_section in sections:
                for other in other_section["functions"]:
                    if other["name"] == function["name"] and (
                        other_section is not section or other["vram"] != start
                    ):
                        raise ValueError(f'Manual function moved: {function["name"]}')
            # Override the ELF's name/size at this address, including suffixed names.
            section["functions"] = [f for f in section["functions"] if f["vram"] != start]
            section["functions"].append(dict(function))
    return sections


def render(sections, item_key):
    lines = ["# Autogenerated from an ELF via N64Recomp"]
    for section in sections:
        lines.extend(["[[section]]", f'name = {json.dumps(section["name"])}'])
        for key in ("rom", "vram", "size"):
            if key in section:
                lines.append(f"{key} = 0x{section[key]:X}")
        for key in ("relocs", item_key):
            if key not in section:
                continue
            lines.extend(["", f"{key} = ["])
            for item in sorted(section[key], key=lambda s: (s["vram"], s.get("name", ""))):
                fields = [
                    f"{k} = {json.dumps(v) if isinstance(v, str) else f'0x{v:X}'}"
                    for k, v in item.items()
                ]
                lines.append("    { " + ", ".join(fields) + " },")
            lines.append("]")
        lines.append("")
    return "\n".join(lines) + "\n"


def generate(elf, recompiler, manual, output):
    with tempfile.TemporaryDirectory(prefix="sk2-symbols-") as directory:
        work = Path(directory)
        config = work / "elf.toml"
        config.write_text(
            "[input]\n"
            f"elf_path = {json.dumps(str(elf.resolve()))}\n"
            "entrypoint = 0x80000400\n"
            'output_func_path = "unused"\n'
        )
        subprocess.run([str(recompiler.resolve()), str(config), "--dump-context"], cwd=work, check=True)
        functions = tomllib.loads((work / "dump.toml").read_text())["section"]
        data = tomllib.loads((work / "data_dump.toml").read_text())["section"]
        apply_manual(functions, tomllib.loads(manual.read_text())["section"])
        rendered = {"dump.toml": render(functions, "functions"), "data_dump.toml": render(data, "symbols")}
        # Parse both outputs before replacing either destination.
        for content in rendered.values():
            tomllib.loads(content)
        output.mkdir(parents=True, exist_ok=True)
        for name, content in rendered.items():
            (output / name).write_text(content)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--elf", type=Path, required=True)
    parser.add_argument("--recompiler", type=Path, required=True)
    parser.add_argument("--manual", type=Path, default=Path(__file__).resolve().parents[1] / "manual_symbols.toml")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    generate(args.elf, args.recompiler, args.manual, args.output)
